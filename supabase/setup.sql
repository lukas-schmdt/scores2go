create extension if not exists pg_cron;

-- ─── Tables ────────────────────────────────────────────────────────────────

-- Score catalogue. Mirrors the Score.id values in lib/data/scores; the app
-- only reads id and popularity_last_7d.
create table public.scores (
  id bigint not null,
  name character varying not null,
  display character varying not null,
  description text null,
  popularity_last_7d smallint not null default 0,
  constraint scores_pkey primary key (id),
  constraint scores_popularity_last_7d_check check (
    popularity_last_7d >= 0 and popularity_last_7d <= 100
  )
);

create table public.user_favorites (
  user_id uuid not null default auth.uid(),
  score_id bigint not null,
  "timestamp" timestamp with time zone null default now(),
  "position" smallint null default '0'::smallint,
  constraint user_favorites_pkey primary key (user_id, score_id),
  constraint user_favorites_score_id_fkey foreign key (score_id) references public.scores (id)
    on delete cascade,
  constraint user_favorites_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade
);

create table public.user_score_collections (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  display character varying not null,
  user_id uuid not null default auth.uid(),
  constraint user_score_collections_pkey primary key (id),
  constraint user_score_collections_user_id_fkey foreign key (user_id) references auth.users (id)
    on update cascade on delete cascade
);

create index user_score_collections_user_id_idx on public.user_score_collections (user_id);

create table public.score_collection_scores (
  user_score_collection_id bigint not null,
  score_id bigint not null,
  created_at timestamp with time zone not null default now(),
  user_id uuid not null default auth.uid(),
  constraint score_collection_scores_pkey primary key (user_score_collection_id, score_id),
  constraint score_collection_scores_score_id_fkey foreign key (score_id) references public.scores (id)
    on update cascade on delete cascade,
  constraint score_collection_scores_user_score_collection_id_fkey foreign key (user_score_collection_id)
    references public.user_score_collections (id) on update cascade on delete cascade,
  constraint score_collection_scores_user_id_fkey foreign key (user_id) references auth.users (id)
    on delete cascade
);

-- Insert-only from the client. user_id is null for anonymous feedback (the
-- default auth.uid() yields null for anon).
create table public.user_feedback (
  user_id uuid null default auth.uid(),
  created_at timestamp with time zone not null default now(),
  feedback character varying null,
  stars smallint null,
  id bigint generated by default as identity not null,
  constraint user_feedback_pkey primary key (id),
  constraint user_feedback_user_id_fkey foreign key (user_id) references auth.users (id) on delete cascade,
  constraint user_feedback_feedback_length check (char_length(feedback::text) <= 2000),
  constraint user_feedback_not_empty check (
    stars is not null or coalesce(trim(both from feedback), ''::text) <> ''::text
  ),
  constraint user_feedback_stars_range check (stars >= 1 and stars <= 5)
);

-- Anonymous usage counts, logged from openScoreEntry. No user_id by design.
create table public.score_opens (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  score_id integer not null,
  platform text null,
  locale text null,
  constraint score_opens_pkey primary key (id),
  constraint score_opens_locale_check check (char_length(locale) <= 8),
  constraint score_opens_platform_check check (char_length(platform) <= 16),
  constraint score_opens_score_id_check check (score_id > 0)
);

create index score_opens_created_at_idx on public.score_opens using btree (created_at);

-- ─── Row Level Security ────────────────────────────────────────────────────
-- The publishable key in lib/main.dart is public; these policies are what
-- protect user data.

alter table public.scores enable row level security;
alter table public.user_favorites enable row level security;
alter table public.user_score_collections enable row level security;
alter table public.score_collection_scores enable row level security;
alter table public.user_feedback enable row level security;
alter table public.score_opens enable row level security;

-- scores: public read
create policy "Enable read access for all users" on public.scores for select to public
  using (true);

-- user_favorites: owner-only (the double space in the name is as in production)
create policy "Users  can operate on own rows" on public.user_favorites for all to public
  using ((select auth.uid()) is not null and (select auth.uid()) = user_id)
  with check ((select auth.uid()) is not null and (select auth.uid()) = user_id);

-- user_score_collections: owner-only
create policy "Owner select" on public.user_score_collections for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "Owner insert" on public.user_score_collections for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "Owner update" on public.user_score_collections for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "Enable delete for users based on user_id" on public.user_score_collections
  for delete to public using ((select auth.uid()) = user_id);

-- score_collection_scores: ownership via parent collection
create policy "Owner select" on public.score_collection_scores for select to authenticated
  using (exists (select 1 from public.user_score_collections c
                 where c.id = user_score_collection_id and c.user_id = (select auth.uid())));
create policy "Owner insert" on public.score_collection_scores for insert to authenticated
  with check ((select auth.uid()) = user_id
              and exists (select 1 from public.user_score_collections c
                          where c.id = user_score_collection_id and c.user_id = (select auth.uid())));
create policy "Owner delete" on public.score_collection_scores for delete to authenticated
  using (exists (select 1 from public.user_score_collections c
                 where c.id = user_score_collection_id and c.user_id = (select auth.uid())));

-- user_feedback: insert-only, no read access
create policy "Own insert" on public.user_feedback for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "Anon insert" on public.user_feedback for insert to anon
  with check (user_id is null);

-- score_opens: insert-only, no read access
create policy "Insert only" on public.score_opens for insert to anon, authenticated
  with check (true);

-- ─── Popularity ────────────────────────────────────────────────────────────
-- scores.popularity_last_7d: percentile rank (0–100) of each score's open
-- count over the last 7 days. 100 = most opened; scores with no opens tie at
-- the bottom and get 0.

create or replace function public.refresh_score_popularity()
returns void language sql security definer set search_path = public as $$
  with counts as (
    select score_id, count(*) as n from score_opens
    where created_at > now() - interval '7 days' group by score_id
  ), ranked as (
    select s.id,
           round(100 * percent_rank() over (order by coalesce(c.n, 0)))::smallint as p
    from scores s left join counts c on c.score_id = s.id
  )
  update scores s set popularity_last_7d = r.p
  from ranked r where s.id = r.id;
$$;
-- Server-side only: clients must not be able to trigger it via RPC.
revoke execute on function public.refresh_score_popularity() from public, anon, authenticated;

-- Hourly. Scheduling under the same name replaces the existing job.
select cron.schedule('refresh-score-popularity', '0 * * * *',
  $$select public.refresh_score_popularity()$$);

